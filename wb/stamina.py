"""体力「是否超上限」判据（顶部药丸底色：亮黄 = 超上限，暗棕 = 上限内）。

为什么不用 OCR（2026-10-13 实测结论）
------------------------------------
顶部那行「292/120」是**独立的第 5 套字形**（大号白字 + 黑描边，宽高比 ≈1.3）：
按高归一后与 `templates/mdigits` 逐字比对，正确数字只得 **0.18~0.46**，错误数字
反而更高 —— 又一次印证「跨字体套用必错」。要 OCR 就得再建一套字形并凑齐 0-9。

但本用例只需要一个**布尔量**「是否 >120」→ 游戏自己给了更稳的信号：
**体力超上限时药丸底色是亮黄，掉回上限内立即变暗棕**。
    212/120（超）   黄像素占比 **0.472**   ← 2026-10-13 真帧 shots/_cs_pill_over.png
     48/120（正常） 黄像素占比 **0.026**   ← 2026-10-13 真帧 shots/_cs_pill_ok.png
分离度 ~18 倍 → 阈值 0.20，比 OCR 简单且免疫字形漂移。

⭐ **取样框必须落在体力数字的右侧**（2026-10-13 定版，前后踩了两个坑）
   坑一：药丸是**两段**，最左有个**黄色倒计时小标**（未满上限才有）→ 不能从左端取。
   坑二（更隐蔽）：**体力数字本身就是金黄色**，围着数字取会把「上限内」也读出
     0.12~0.15（离阀值只剩 40%），而且**读数随体力升高而涨** → 接近上限时假阳
     → 实跑从 175 一路扫到 **70**（过冲 ~50）。
   扫描 dx=20..380 step=20（真帧 70 vs 175，首页/面板各一组）后定版：
     dx=140 宽 45 → 上限内 **0.008~0.04** / 超上限 **0.52~0.60**（余量 13 倍）。
   对照：数字正上（dx≈100）是 0.429/0.427 —— **完全分不开**（旧框能勉强用是因为
   它宽 115、跨到了右侧干净区；一旦体力变高、数字区变黄，余量就没了）。

几何口径
--------
药丸区**相对 `stamina_entry` 模板命中中心**取（`Screen.find` 返回的是命中中心，
实测两帧分别是 (44,135)@833x1515 与 (45,136)@845x1521，相对位置几乎重合），
再按帧宽高缩放到基准 845x1521 → 换窗口尺寸/分辨率都不用重标。

⭐ **压暗免疫**（2026-10-13）: 扫荡面板会把它身后的整个背景压暗（顶栏药丸一起），
   但压暗是**纯亮度缩放 ~0.26 倍**（色相/饱和度原封不动: 实测 V 255→66、S 200→201）
   → 所以判据只用**色相+饱和度、不加明度门限**，面板态与首页态读数完全一致
     （212/120: 首页 0.472 / 面板 0.475）→ **面板里就能就地读**，不用每轮进出面板。
   ⚠ 一旦有人给掩膜加回 V 门限，面板态会瞬间归零 → 误判「不用清」而提前收工。

⚠ 已知过冲：**上限值本身（=120/120）药丸也是黄的** → 恰好在 120 时会多扫一轮
   （≈10 体力）。一次扫荡本来就是 10~15 的整数跳，不可能精确停在 120，属可接受过冲。
"""
from __future__ import annotations

import os
import sys

import cv2
import numpy as np

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

REF_W, REF_H = 845, 1521        # 基准帧（点击基线尺寸）
ENTRY_TH = 0.93                 # stamina_entry 命中阈值（实测 0.97+）
PILL_DX, PILL_DY = 140, -40      # 取样框左上角相对「入口命中中心」的偏移（基准尺度）
                                 # ⚠ **2026-10-13 从 110 右移到 140，宽度 115 收窄到 45**：
                                 #   旧框罩在「体力数字」上，而**数字本身就是金黄色** →
                                 #   上限内也读 0.12~0.15（离阀值只剩 40% 余量），且随体力升高而涨
                                 #   → 接近上限时假阳 → 实跑过冲 175→70。
                                 #   扫描 dx=20..380 step20 实测（首页/面板各两帧 70 vs 175）：
                                 #     dx=100: 0.429 / 0.427 ← 完全分不开（数字区）
                                 #     dx=140: 0.000 / 0.459    dx=160: 0.003 / 0.598 ← 最优区
                                 #   右移到药丸右段（数字右侧的底/光效区）后：上限内 0.008~0.04。
                                 # ⚠ 这个位置同时避开了最左的黄色倒计时小标（未满上限时才有）
PILL_W, PILL_H = 45, 55          # 取样框尺寸（基准尺度；宽 45 才是「干净区」，加宽会把数字圈回来）
MIN_YELLOW = 0.20               # 黄占比 ≥ 此值 = 超上限（实测 0.52 vs 0.04，余量 13 倍）


def yellow_frac(frame: np.ndarray, cx: float, cy: float) -> float:
    """药丸区「亮黄」像素占比。

    frame: 整帧；cx/cy: stamina_entry 命中中心（帧坐标）。
    亮黄 = 色相 15~40（金黄）+ 高饱和 + 高明度；暗棕底靠 V 挡掉。
    """
    h, w = frame.shape[:2]
    x0 = int(cx + PILL_DX * w / REF_W)
    y0 = int(cy + PILL_DY * h / REF_H)
    x1 = x0 + max(1, int(PILL_W * w / REF_W))
    y1 = y0 + max(1, int(PILL_H * h / REF_H))
    x0, y0 = max(0, x0), max(0, y0)
    roi = frame[y0:max(y0 + 1, y1), x0:max(x0 + 1, x1)]
    if roi.size == 0:
        return 0.0
    hsv = cv2.cvtColor(roi, cv2.COLOR_BGR2HSV)
    hh, ss = hsv[..., 0], hsv[..., 1]
    # ⚠ **绝不能加明度(V)门限**：面板会把背景压成 ~0.26 倍亮度（色相/饱和度不变），
    #   加 V 门限会让面板态读数归零（292/120 读作 0.000）→ 误判「不用清」提前收工。
    #   只用色相+饱和度即可：超上限 0.49（首页 0.493 / 面板 0.494 一致）vs 正常 0.05。
    mask = (hh >= 15) & (hh <= 40) & (ss > 110)
    return float(mask.mean())


def over_cap(sc) -> bool | None:
    """体力是否超上限。

    True=超上限（亮黄）/ False=上限内 / **None=认不出**（入口未命中或取帧失败）
    —— 调用方遇到 None 必须保守处理（别继续盲扫）。

    面板态可直接调用（压暗免疫，见模块 docstring）。
    """
    hit = sc.find("stamina_entry", ENTRY_TH)
    if hit is None:
        return None
    return yellow_frac(sc.grab(), hit[0], hit[1]) >= MIN_YELLOW


def state(sc) -> str:
    """人类可读状态: "over" / "ok" / "unknown"。"""
    o = over_cap(sc)
    return "over" if o is True else ("ok" if o is False else "unknown")
